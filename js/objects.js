// ---- helpers ------------------------------------------------------------------
// opts: any MeshStandardMaterial option, plus r: [rx, ry, rz] rotation and s: [sx, sy, sz] scale.
const mat = (color, o = {}) =>
  new THREE.MeshStandardMaterial({ color, roughness: 0.75, metalness: 0, flatShading: true, ...o });

function mesh(geo, color, x = 0, y = 0, z = 0, o = {}) {
  const { r, s, ...m } = o;
  const msh = new THREE.Mesh(geo, mat(color, m));
  msh.position.set(x, y, z);
  if (r) msh.rotation.set(r[0], r[1], r[2]);
  if (s) msh.scale.set(s[0], s[1], s[2]);
  msh.castShadow = true;
  msh.receiveShadow = true;
  return msh;
}
const box = (w, h, d, c, x, y, z, o) => mesh(new THREE.BoxGeometry(w, h, d), c, x, y, z, o);
const cyl = (rt, rb, h, c, x, y, z, o, seg = 14) => mesh(new THREE.CylinderGeometry(rt, rb, h, seg), c, x, y, z, o);
const tube = (rt, rb, h, c, x, y, z, o, seg = 16) => mesh(new THREE.CylinderGeometry(rt, rb, h, seg, 1, true), c, x, y, z, { side: THREE.DoubleSide, ...o });
const sph = (r, c, x, y, z, o, detail = 1) => mesh(new THREE.IcosahedronGeometry(r, detail), c, x, y, z, o);
const ball = (r, c, x, y, z, o) => mesh(new THREE.SphereGeometry(r, 18, 12), c, x, y, z, { flatShading: false, ...o });
const cone = (r, h, c, x, y, z, o, seg = 12) => mesh(new THREE.ConeGeometry(r, h, seg), c, x, y, z, o);
const tor = (R, r, c, x, y, z, o, arc = Math.PI * 2) => mesh(new THREE.TorusGeometry(R, r, 8, 28, arc), c, x, y, z, o);
const oct = (r, c, x, y, z, o) => mesh(new THREE.OctahedronGeometry(r, 0), c, x, y, z, o);
const dod = (r, c, x, y, z, o) => mesh(new THREE.DodecahedronGeometry(r, 0), c, x, y, z, o);
const glow = (c, i = 1.2) => ({ emissive: c, emissiveIntensity: i });
const metal = { metalness: 0.7, roughness: 0.35 };
const gold = { metalness: 0.7, roughness: 0.35, emissive: '#7a5a10', emissiveIntensity: 0.3 };
const glass = { transparent: true, opacity: 0.35, roughness: 0.1 };
const PI = Math.PI;

function rng(seed) {
  let s = seed;
  return () => ((s = (s * 16807) % 2147483647) / 2147483647);
}

const G = (...children) => {
  const g = new THREE.Group();
  children.flat().forEach((c) => g.add(c));
  return g;
};
const at = (g, x, y, z, ry = 0) => { g.position.set(x, y, z); g.rotation.y = ry; return g; };

